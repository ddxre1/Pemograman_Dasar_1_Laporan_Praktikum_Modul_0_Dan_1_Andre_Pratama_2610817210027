totalLaps = 5
totalDistance = 14

print("Diketahui :")
print(f"Pak Dengklek mengelilingi taman = {totalLaps} Putaran")
print(f"Jarak tempuh Pak Dengklek = {totalDistance} Kilometer")

distancePerLap = totalDistance / totalLaps
radius = distancePerLap / (2 * 3.14)

print("\nJawaban : ")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {radius:.2f} Kilometer")